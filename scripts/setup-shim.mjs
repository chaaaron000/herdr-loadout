#!/usr/bin/env node
/**
 * Install `herdr-loadout` launchers.
 *
 * Herdr plugins cannot add subcommands to the `herdr` binary, so the CLI is a
 * separate executable. The launchers give agents and humans a stable command
 * name without this plugin ever editing PATH or a shell profile.
 *
 *   node scripts/setup-shim.mjs                 launchers in the plugin config dir
 *   node scripts/setup-shim.mjs --dir <path>    launchers in <path> (a folder already on PATH)
 *   node scripts/setup-shim.mjs --refresh       rewrite launchers that already exist, silently
 *
 * `--refresh` runs from the [[startup]] hook, so a launcher installed once keeps
 * pointing at the plugin after a reinstall moves it. It never creates new ones.
 */
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import { configDir, sourceRoot } from "../src/core/paths.mjs";

const REINSTALL_HINT = "herdr plugin action invoke herdr-loadout.install-shim";

/** Launcher file name -> contents, for a CLI entry at `binScript`. */
export function launchers(binScript) {
  return {
    "herdr-loadout.cmd": [
      "@echo off",
      "rem generated by herdr-loadout; re-run: node scripts/setup-shim.mjs",
      `if not exist "${binScript}" (`,
      `  echo herdr-loadout: plugin not found at its install path. Re-run: ${REINSTALL_HINT} 1>&2`,
      "  exit /b 1",
      ")",
      `node "${binScript}" %*`,
      "",
    ].join("\r\n"),
    "herdr-loadout.ps1": [
      "# generated by herdr-loadout; re-run: node scripts/setup-shim.mjs",
      `if (-not (Test-Path -LiteralPath "${binScript}")) {`,
      `  [Console]::Error.WriteLine("herdr-loadout: plugin not found at its install path. Re-run: ${REINSTALL_HINT}")`,
      "  exit 1",
      "}",
      `node "${binScript}" @args`,
      "exit $LASTEXITCODE",
      "",
    ].join("\n"),
    "herdr-loadout": [
      "#!/usr/bin/env sh",
      "# generated by herdr-loadout; re-run: node scripts/setup-shim.mjs",
      `if [ ! -f "${binScript}" ]; then`,
      `  echo "herdr-loadout: plugin not found at its install path. Re-run: ${REINSTALL_HINT}" >&2`,
      "  exit 1",
      "fi",
      `exec node "${binScript}" "$@"`,
      "",
    ].join("\n"),
  };
}

/**
 * Write launchers into `target`. With `onlyExisting`, files that are not already
 * there are skipped. Returns the paths written.
 */
export function writeLaunchers(target, binScript, { onlyExisting = false } = {}) {
  fs.mkdirSync(target, { recursive: true });
  const written = [];
  for (const [name, contents] of Object.entries(launchers(binScript))) {
    const file = path.join(target, name);
    if (onlyExisting && !fs.existsSync(file)) continue;
    fs.writeFileSync(file, contents);
    if (name === "herdr-loadout") fs.chmodSync(file, 0o755);
    written.push(file);
  }
  return written;
}

function main() {
  const { values } = parseArgs({
    options: { dir: { type: "string" }, refresh: { type: "boolean", default: false } },
    strict: true,
  });
  const binScript = path.join(sourceRoot(), "bin", "herdr-loadout.mjs");
  const target = path.resolve(values.dir ?? configDir());

  if (values.refresh) {
    // Never create the config dir or new launchers from a startup hook.
    if (fs.existsSync(target)) writeLaunchers(target, binScript, { onlyExisting: true });
    return;
  }

  const written = writeLaunchers(target, binScript);
  const lines = [`Installed launchers in ${target}:`, ...written.map((file) => `  ${file}`), ""];
  if (values.dir) {
    lines.push(`Call it as \`herdr-loadout\` if ${target} is on PATH.`);
  } else {
    lines.push(
      "Agents find it without PATH:",
      '  "$(herdr plugin config-dir herdr-loadout)/herdr-loadout" list --compact',
      "",
      "To call `herdr-loadout` from any shell, install into a folder already on PATH:",
      "  node scripts/setup-shim.mjs --dir <folder on PATH>",
    );
  }
  lines.push("", "The CLI also runs directly without any launcher:", `  node "${binScript}" list --compact`, "");
  process.stdout.write(lines.join("\n"));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
